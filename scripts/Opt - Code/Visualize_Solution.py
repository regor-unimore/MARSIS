import argparse
from pathlib import Path
import numpy as np
import matplotlib.pyplot as plt
from opt_cli import DEFAULT_INSTANCE_DIR, DEFAULT_GENERAL_DIR, DEFAULT_OUTPUT_DIR

#  Define INSTANCE
parser = argparse.ArgumentParser(description="Code to visualize the solution generated by any of the optimization codes",
                                 formatter_class=argparse.ArgumentDefaultsHelpFormatter)
parser.add_argument('instance_name', type=str, help="Name of the instance (e.g. M_10_134_4)")
parser.add_argument('solution', type=Path, help="Solution file generated by one of the optimization codes "
                                                "(e.g. output/ModelSolution_M_10_268_4.txt)")
parser.add_argument('--repetition', type=int, default=1,
                    help="Solution to draw when the file contains more than one solution (matheuristics, one per repetition)")
parser.add_argument('--instance-dir', type=Path, default=DEFAULT_INSTANCE_DIR,
                    help="Directory containing the extracted instance folders")
parser.add_argument('--general-dir', type=Path, default=DEFAULT_GENERAL_DIR,
                    help="Directory containing the general data files (SouthPole_contour.dat, ...)")
parser.add_argument('--output-dir', type=Path, default=DEFAULT_OUTPUT_DIR, help="Directory where the figure is saved")
parser.add_argument('--show', action='store_true', help="Also display the figure on screen")
args = parser.parse_args()
name = args.instance_name

name_char = name.split('_')

#  Parameters
G = name_char[1]
L = name_char[2]
NC = name_char[3]
gra = {'01': 1000, '02': 2000, '03': 3000, '05': 5000, '10': 10000}
nO = 113651         # number of observations

#  South Pole contour
cox = []
coy = []
with open(args.general_dir / "SouthPole_contour.dat", "r") as file:
    for line in file:
        temp = line.split(",")
        cox.append(float(temp[0]))
        coy.append(float(temp[1]))

#  Information on PIs
x = []
y = []
wPI = []
with open(args.instance_dir / name / f"{name}(1).txt", 'r') as file:
    lines = file.readlines()
    nPI = len(lines)        # number of PI
    for line in lines:
        line = list(line.strip().split(' '))
        x.append(float(line[1]))
        y.append(float(line[2]))
        wPI.append(int(line[6]))

#  PI in observations
with open(args.instance_dir / name / f"{name}(2).txt", "r") as file:
    PIinO = [[int(i) for i in line.strip().split("\t")]
            if line != "" and line != "\n" else [] for line in file.readlines()]

# Solution: the summary lines written by the codes are skipped, the remaining lines contain one value per observation
values = []
with open(args.solution, "r") as file:
    for line in file:
        try:
            values.append(round(float(line)))
        except ValueError:
            pass  # summary line
if len(values) == 0 or len(values) % nO != 0:
    parser.error(f"{args.solution} does not contain solutions with {nO} values")
n_solutions = len(values) // nO
if not 1 <= args.repetition <= n_solutions:
    parser.error(f"--repetition must be between 1 and {n_solutions}")
selected = values[(args.repetition - 1) * nO: args.repetition * nO]

visited = [0]*nPI
for i in range(nO):
    if selected[i] == 1:
        for j in PIinO[i]:
            visited[j] = 1
print(f"selected observations = {sum(selected)}")
print(f"number of PI visited = {sum(visited)}")

# Draw contour
plt.xlim(1.1 * min(cox), 1.1 * max(cox))
plt.ylim(1.1 * min(coy), 1.1 * max(coy))
plt.plot(cox, coy)

fig = plt.gcf()  # get the current figure
ax = fig.gca()  # get the current axes

# Draw PIs according to the AOIs
for i in range(nPI):
    if visited[i] == 1 and wPI[i] == 1:
        ax.add_artist(
            plt.Rectangle((x[i], y[i]), gra[G], gra[G], lw=None, facecolor='blue', edgecolor=None))

    if visited[i] == 1 and wPI[i] == 0:
        ax.add_artist(
            plt.Rectangle((x[i], y[i]), gra[G], gra[G], lw=None, facecolor='gray', edgecolor=None))

plt.grid(visible=False)
args.output_dir.mkdir(parents=True, exist_ok=True)
suffix = f"_rep{args.repetition}" if n_solutions > 1 else ""
figure = args.output_dir / f"{args.solution.stem}{suffix}.pdf"
plt.savefig(figure)
print(f"figure saved to {figure}")
if args.show:
    plt.show()
